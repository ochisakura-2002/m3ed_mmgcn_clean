SCHEMA = "s2d_frozen_linear_b_prediction_export_v1"
EXPECTED_ROWS = {"train": 4818, "dev": 978}
PROBABILITY_TOLERANCE = 1e-6
NORMALIZATION = "00_provenance/normalization/b.json"
IN_SAMPLE_NOTE = (
    "These Train predictions are generated by the frozen Linear-B seed100 probe "
    "that was itself fitted on the same Train split. They are intended for the "
    "low-capacity exploratory decision-gate experiment and are not claimed to "
    "be unbiased out-of-fold stacking predictions."
)


def reject_test_path(value):
    # Lexical check precedes resolve/stat/open, including Windows paths on Linux.
    text = re.sub(r"([a-z])([A-Z])", r"\1_\2", str(value))
    if re.search(r"(^|[^a-z])test(?:s|ing|set)?(?=$|[^a-z])", text, re.IGNORECASE):
        raise ValueError(f"Test-named paths are forbidden: {value}")


def direct_file(directory, name):
    reject_test_path(name)
    return banks.direct_file(directory, name)


def validate_predictions(ids, labels, probabilities):
    if (not ids or any(not isinstance(uid, str) or not uid.strip() for uid in ids)
            or len(set(ids)) != len(ids)):
        raise ValueError("Prediction IDs must be non-empty and unique")
    if (labels.dtype != torch.int64 or labels.shape != (len(ids),)
            or bool(((labels < 0) | (labels >= 6)).any())):
        raise ValueError("Invalid prediction labels")
    if (probabilities.shape != (len(ids), 6) or not probabilities.is_floating_point()
            or not bool(torch.isfinite(probabilities).all())
            or bool(((probabilities < 0) | (probabilities > 1)).any())
            or not torch.allclose(probabilities.double().sum(-1),
                                  torch.ones(len(ids), dtype=torch.float64),
                                  atol=PROBABILITY_TOLERANCE, rtol=0)):
        raise ValueError("Invalid probabilities: finite, nonnegative, sum-to-one required")


def reproduce_dev(path, ids, labels, probabilities):
    validate_predictions(ids, labels, probabilities)
    with path.open(encoding="utf-8", newline="") as stream:
        reader = csv.DictReader(stream)
        if tuple(reader.fieldnames or ()) != reports.PREDICTION_FIELDS:
            raise ValueError("Dev reference prediction schema mismatch")
        rows = list(reader)
    if len(rows) != EXPECTED_ROWS["dev"] or len(rows) != len(ids):
        raise ValueError("Dev reference row_count mismatch")
    if any(set(row) != set(reports.PREDICTION_FIELDS) or any(value is None for value in row.values())
           for row in rows):
        raise ValueError("Dev reference prediction row schema mismatch")
    reference_ids = [row["utterance_id"] for row in rows]
    try:
        reference_labels = torch.tensor([int(row["true_label"]) for row in rows], dtype=torch.int64)
        reference_predictions = torch.tensor([int(row["pred_label"]) for row in rows], dtype=torch.int64)
        reference_probabilities = torch.tensor(
            [[float(row[f"prob_{c}"]) for c in range(6)] for row in rows], dtype=torch.float64)
    except (TypeError, ValueError, RuntimeError) as error:
        raise ValueError("Invalid Dev reference values") from error
    validate_predictions(reference_ids, reference_labels, reference_probabilities)
    if reference_ids != ids:
        raise ValueError("Dev utterance_id/order mismatch")
    if not torch.equal(reference_labels, labels):
        raise ValueError("Dev true_label mismatch")
    if (not torch.equal(reference_predictions, reference_probabilities.argmax(-1))
            or not torch.equal(reference_predictions, probabilities.argmax(-1))):
        raise ValueError("Dev pred_label mismatch")
    difference = float((reference_probabilities - probabilities.double()).abs().max())
    if difference > PROBABILITY_TOLERANCE:
        raise ValueError(f"Dev probability mismatch: max_abs_difference={difference:.17g}")
    return difference


def load_normalization(path, bank):
    stats = banks.read_json(path)
    if (stats.get("feature") != "b" or stats.get("field") != banks.FEATURES["b"]
            or stats.get("fit_split") != "train" or stats.get("axes") != ["utterance", "slot"]
            or type(stats.get("count")) is not int or stats["count"] != len(bank.ids["train"]) * 16
            or stats.get("ddof") != 0 or stats.get("epsilon") != 1e-6
            or stats.get("train_index_identity") != bank.metadata_identities["train/index.json"]):
        raise ValueError("Frozen B normalization contract / Train index mismatch")
    values = []
    for name in ("mean", "std"):
        raw = stats.get(name)
        if (not isinstance(raw, list) or len(raw) != 768
                or any(type(value) not in (int, float) for value in raw)):
            raise ValueError(f"Invalid frozen normalization {name}")
        value = torch.tensor(raw, dtype=torch.float32)
        if not bool(torch.isfinite(value).all()):
            raise ValueError(f"Non-finite frozen normalization {name}")
        values.append(value)
    mean, std = values
    if bool((std < torch.tensor(1e-6, dtype=torch.float32)).any()):
        raise ValueError("Frozen normalization std below epsilon")
    return mean, std


def load_artifacts(run_dir):
    if run_dir.parts[-3:] != ("03_linear", "b", "seed100"):
        raise ValueError("Expected Q1 archive/03_linear/b/seed100")
    archive = run_dir.parents[2]
    complete_path = direct_file(archive, "complete.json")
    complete = banks.read_json(complete_path)
    if (complete.get("schema_version") != "s2d_q1_probe_archive_v1"
            or complete.get("status") != "complete" or complete.get("mode") != "all_30_probes"
            or complete.get("trainable_runs") != 30 or complete.get("test_accessed") is not False
            or not isinstance(complete.get("artifacts"), dict)):
        raise ValueError("Completed Train/Dev Q1 archive required")
    provenance_dir = archive / "00_provenance"
    normalization_dir = provenance_dir / "normalization"
    for directory in (archive / "03_linear", run_dir.parent, run_dir, provenance_dir, normalization_dir):
        if directory.is_symlink() or directory.resolve() != directory:
            raise ValueError("Q1 artifact directories must not contain symlinks")
    paths = {
        "config": direct_file(run_dir, "config.json"),
        "checkpoint": direct_file(run_dir, "best_model.pt"),
        "dev_reference": direct_file(run_dir, "predictions_dev.csv"),
        "normalization": direct_file(normalization_dir, "b.json"),
        "provenance": direct_file(provenance_dir, "provenance.json"),
        "bank_reference": direct_file(provenance_dir, "feature_bank_reference.json"),
    }
    identities = {}
    for name, path in paths.items():
        identities[name] = banks.identity(path)
        if complete["artifacts"].get(path.relative_to(archive).as_posix()) != identities[name]:
            raise ValueError(f"Q1 archive identity mismatch: {name}")
    config = banks.read_json(paths["config"])
    if (config.get("model") != "L-B" or config.get("feature") != "b"
            or config.get("probe_type") != "linear" or type(config.get("seed")) is not int
            or config["seed"] != 100 or config.get("normalization") != NORMALIZATION
            or config.get("normalization_identity") != identities["normalization"]
            or config.get("selection_split") != "dev" or config.get("selection_metric") != "weighted_f1"):
        raise ValueError("Frozen Linear-B seed100 config / normalization identity mismatch")
    protocol = validate_config(config.get("protocol"))
    if protocol["normalization"] != "train_channel_standardize" or not protocol["enabled"]:
        raise ValueError("Train-channel-standardized Q1 probe required")
    provenance = banks.read_json(paths["provenance"])
    if (provenance.get("device") not in {"cpu", "cuda"} or provenance.get("test_accessed") is not False
            or not isinstance(provenance.get("git_head"), str) or not provenance["git_head"]):
        raise ValueError("Invalid Q1 runtime provenance")
    paths["complete"] = complete_path
    identities["complete"] = banks.identity(complete_path)
    return paths, identities, protocol, provenance


@torch.inference_mode()
def export_predictions(bank_dir, probe_run_dir, split, output_dir, *, device=None):
    # This is also the programmatic boundary; no path resolution or input IO first.
    if split not in ("train", "dev"):
        raise ValueError("Only train/dev allowed; Test and aggregate splits are forbidden")
    if device is not None and device not in ("cpu", "cuda"):
        raise ValueError("device must be cpu or cuda")
    for path in (bank_dir, probe_run_dir, output_dir):
        reject_test_path(path)
    bank_dir, run_dir, output_dir = map(resolve_path, (bank_dir, probe_run_dir, output_dir))
    for path in (bank_dir, run_dir, output_dir):
        reject_test_path(path)
    if run_dir.parts[-3:] != ("03_linear", "b", "seed100"):
        raise ValueError("Expected Q1 archive/03_linear/b/seed100")
    archive = run_dir.parents[2]
    for source in (bank_dir, archive):
        if output_dir == source or source in output_dir.parents or output_dir in source.parents:
            raise ValueError("Export output must be disjoint from bank and Q1 archive")
    if output_dir.exists():
        raise FileExistsError(f"Refusing existing export directory: {output_dir}")

    paths, identities, protocol, provenance = load_artifacts(run_dir)
    device = provenance["device"] if device is None else device
    if device == "cuda" and not torch.cuda.is_available():
        raise RuntimeError("Requested CUDA is unavailable; no CPU fallback")
    bank = banks.FeatureBank(bank_dir)  # Explicit train/dev only; never enumerate inputs.
    for name, expected in EXPECTED_ROWS.items():
        if len(bank.ids[name]) != expected:
            raise ValueError(f"Frozen {name} row_count mismatch: expected {expected}")
    reference = banks.read_json(paths["bank_reference"])
    if (reference.get("metadata_identities") != bank.metadata_identities
            or reference.get("shard_identities") != bank.shard_identities):
        raise ValueError("Bank identity differs from frozen Q1 bank reference")
    mean, std = load_normalization(paths["normalization"], bank)
    model = LinearProbe()
    model.load_state_dict(torch.load(paths["checkpoint"], map_location="cpu", weights_only=True), strict=True)
    model.requires_grad_(False)
    model.to(device).eval()

    before_threads = torch.get_num_threads()
    torch.set_num_threads(protocol["train"]["cpu_threads"])
    try:
        def infer(which):
            # Exactly the original Q1 Linear pooling, affine transform and eval path.
            features = (bank.values(which, banks.FEATURES["b"], pooled=True) - mean) / std
            _, probabilities = evaluate(
                model, features, bank.labels[which], protocol["train"]["batch_size"], device)
            validate_predictions(bank.ids[which], bank.labels[which], probabilities)
            return probabilities

        dev_probabilities = infer("dev")
        difference = reproduce_dev(
            paths["dev_reference"], bank.ids["dev"], bank.labels["dev"], dev_probabilities)
        probabilities = infer("train") if split == "train" else dev_probabilities
        bank.assert_unchanged()
        for name, path in paths.items():
            if banks.identity(path) != identities[name]:
                raise ValueError(f"Frozen Q1 artifact changed during export: {name}")

        prediction_name = f"predictions_{split}.csv"
        rows = [
            dict(utterance_id=uid, true_label=int(bank.labels[split][i]),
                 pred_label=int(probabilities[i].argmax()),
                 **{f"prob_{c}": float(probabilities[i, c]) for c in range(6)})
            for i, uid in enumerate(bank.ids[split])
        ]
        git_head = subprocess.run(
            ["git", "rev-parse", "HEAD"], cwd=PROJECT_ROOT, check=True,
            capture_output=True, text=True).stdout.strip()
        manifest = {
            "schema": SCHEMA, "split": split, "row_count": len(rows),
            "prediction_schema": list(reports.PREDICTION_FIELDS),
            "probe": "Linear-B", "seed": 100, "representation": "S2D-B mean contextual slots",
            "checkpoint_path": str(paths["checkpoint"]), "checkpoint_sha256": identities["checkpoint"]["sha256"],
            "normalization_path": str(paths["normalization"]),
            "normalization_sha256": identities["normalization"]["sha256"],
            "normalization_contract": {
                "fit_split": "train", "axes": ["utterance", "slot"], "ddof": 0, "epsilon": 1e-6,
                "frozen_statistics_reused": True, "refitted": False,
            },
            "bank_identity": {"path": str(bank_dir), "provenance": bank.provenance,
                              "metadata_identities": bank.metadata_identities,
                              "shard_identities": bank.shard_identities},
            "probe_run_dir": str(run_dir), "q1_git_commit": provenance["git_head"],
            "git_commit": git_head, "device": device, "torch": str(torch.__version__),
            "batch_size": protocol["train"]["batch_size"], "cpu_threads": protocol["train"]["cpu_threads"],
            "dev_reference_path": str(paths["dev_reference"]),
            "dev_reference_sha256": identities["dev_reference"]["sha256"],
            "dev_reproduction_status": "PASS", "dev_row_count": len(bank.ids["dev"]),
            "dev_max_abs_prob_diff": difference, "dev_probability_tolerance": PROBABILITY_TOLERANCE,
            "in_sample_base_prediction": split == "train",
            "train_prediction_limitation": IN_SAMPLE_NOTE,
            "test_access": False, "probe_retrained": False,
        }
        # No directory is published until Dev gate, Train inference and integrity pass.
        output_dir.mkdir(parents=True, exist_ok=False)
        reports.atomic_csv(output_dir / prediction_name, rows, reports.PREDICTION_FIELDS)
        manifest["prediction_identity"] = banks.identity(output_dir / prediction_name)
        # Last publication marks a complete export; a CSV alone is not completion.
        reports.atomic_json(output_dir / "prediction_export_manifest.json", manifest)
        return manifest
    finally:
        torch.set_num_threads(before_threads)


def parse_args(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--bank-dir", required=True)
    parser.add_argument("--probe-run-dir", required=True, help="Q1 archive/03_linear/b/seed100")
    parser.add_argument("--split", required=True, choices=("train", "dev"))
    parser.add_argument("--output-dir", required=True, help="New directory outside bank and Q1 archive")
    parser.add_argument("--device", choices=("cpu", "cuda"), help="Default: archived Q1 device; no fallback")
    return parser.parse_args(argv)


def main(argv=None):
    args = parse_args(argv)
    manifest = export_predictions(
        args.bank_dir, args.probe_run_dir, args.split, args.output_dir, device=args.device)
    print(f"DEV_REPRODUCTION=PASS; max_abs_prob_diff={manifest['dev_max_abs_prob_diff']:.17g}; "
          f"{args.split.upper()}_EXPORTED_ROWS={manifest['row_count']}")


if __name__ == "__main__":
    main()
